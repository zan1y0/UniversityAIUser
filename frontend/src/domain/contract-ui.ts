export function defaultValue(schema: Schema, name = ''): unknown {
  const s = displaySchema(schema);
  if ('default' in s) return s.default;
  if ('const' in s) return s.const;
  if (s.oneOf) return defaultValue(s.oneOf[0]!, name);
  if (s.type === 'object')
    return Object.fromEntries(
      Object.entries(s.properties || {})
        .filter(([k]) => s.required?.includes(k))
        .map(([k, v]) => [k, defaultValue(v, k)]),
    );
  if (s.type === 'array') return [];
  if (s.type === 'boolean') return false;
  if (s.enum) return s.enum[0];
  if (s.type === 'integer' || s.type === 'number') {
    if (['year', 'targetYear'].includes(name)) return new Date().getFullYear() + 1;
    if (['fromYear', 'toYear'].includes(name))
      return new Date().getFullYear() - (name === 'fromYear' ? 4 : 1);
    if (name === 'dailyMinutes' || name === 'timeBudget') return 240;
    if (name === 'duration') return 600;
    return s.minimum ?? 0;
  }
  if (s.format === 'date') {
    if (name === 'weekStart') return monday();
    if (name === 'targetDate') return `${new Date().getFullYear() + 1}-12-20`;
    if (name === 'from') {
      const d = new Date();
      d.setDate(d.getDate() - 6);
      return d.toLocaleDateString('en-CA', { timeZone: 'Asia/Shanghai' });
    }
    return today();
  }
  if (s.format === 'date-time')
    return new Date(Date.now() - (name === 'startAt' ? 1500000 : 0)).toISOString();
  if (name === 'examType') return 'math1';
  if (name === 'time' || name === 'reminderTime') return '20:00';
  return '';
}
